  /** As the page states it. Null when the page gives no amount. */
  amountText: string | null;
  /** Largest single award in US dollars, only when the page gives a number. */
  amount: number | null;
  deadline: string | null;
  /** The deadline in words, as the page puts it (time zone included). */
  deadlineText: string | null;
  deadlineRule?: boolean;
