/**
 * Well-known national scholarships and fellowships for students and individuals in the United States,
 * each checked by hand on the sponsor's own official page. Facts only, written as the page states them;
 * the page itself is always one click away in `url`.
 *
 * Monthly re-check: `npx tsx --tsconfig tsconfig.json scripts/check-scholarships.ts` re-fetches every
 * page (politely) and reports dead links and entries whose `watch` text no longer appears, which usually
 * means the deadline moved. Update the entry, set `lastChecked`, and re-run the connector.
 *
 * Rules for entries:
 * - `url` is the sponsor's program page, never a news story or a list site.
 * - `deadline` only when the official page states it for the upcoming cycle. A bare date (YYYY-MM-DD)
 *   means the end of that day; a timestamp with an offset when the page gives a time.
 * - `deadlineRule` marks a date the page states as a yearly rule ("the last Friday in January").
 * - `opensAt` when the page gives the opening date of a window that has not started yet;
 *   `pendingOpen` when it says the window opens later without an exact date.
 * - `openNow` when the page says applications are open but gives no deadline; `rolling` when the
 *   page says applications are accepted year round.
 * - `watch` is a short phrase copied from one of the pages (`url` or `sources`) that carries the
 *   deadline or status. The monthly check flags the entry when the phrase disappears.
 * - `botBlocked` marks hosts that refuse automated requests; those pages are checked in a browser.
 */

